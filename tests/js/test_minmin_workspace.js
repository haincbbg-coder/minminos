const assert = require('node:assert/strict');
const {advance, outline, safeLink} = require('../../dashboard/minmin-workspace.js');
let s=advance(null,{type:'start'});
assert.equal(s.pct,8);
s=advance(s,{type:'tool_call',tool:'POS'});
assert.equal(s.pct,30);
for(let i=0;i<40;i++) s=advance(s,{type:'tool_result'});
assert.ok(s.pct<100,'tool count alone must never claim completion');
s=advance(s,{type:'stream'});assert.equal(s.pct,90);
s=advance(s,{type:'cancelled'});s=advance(s,{type:'turn_done'});
assert.equal(s.phase,'cancelled');assert.equal(s.pct,90);
s=advance(s,{type:'start'});assert.equal(s.pct,8);assert.equal(s.steps,0);
s=advance(s,{type:'error'});s=advance(s,{type:'turn_done'});assert.equal(s.phase,'error');assert.notEqual(s.pct,100);
s=advance(s,{type:'start'});s=advance(s,{type:'turn_done'});assert.equal(s.pct,100);
assert.equal(safeLink('javascript:alert(1)'),'');assert.equal(safeLink('data:text/html,x'),'');assert.equal(safeLink('https://example.com/a'),'https://example.com/a');
const o=outline([{role:'user',text:'**Báo cáo** [hôm qua](https://x.test)'},{role:'assistant',content:'Doanh thu có sẵn. Chưa đủ giá vốn.'}]);
assert.deepEqual(o.requests,['Báo cáo hôm qua']);assert.ok(o.last.includes('Chưa đủ giá vốn'));
assert.deepEqual(outline([]),{requests:[],last:''});
console.log('Min Min progress, summary and safe links: passed');
