const assert = require('assert');
const R = require('../../dashboard/file-shelf-core.js');
const base = 'https://minmin.example/apps/tai-hoa-don/';
assert.equal(R.safeURL('api/tep/1',base), base+'api/tep/1');
assert.equal(R.safeURL('https://photo-stal-17.zdn.vn/a.jpg',base),'https://photo-stal-17.zdn.vn/a.jpg');
for(const url of ['javascript:alert(1)','data:image/png,abc','https://zdn.vn.evil.test/a','https://user:pass@zdn.vn/a','https://zdn.vn:444/a','http://zdn.vn/a','https://127.0.0.1/a']) assert.equal(R.safeURL(url,base),'');
assert.throws(()=>R.validate([],{size:0}),/trống/);
assert.throws(()=>R.validate([],{size:R.MAX_FILE+1}),/20 MB/);
assert.throws(()=>R.validate(Array.from({length:40},()=>({blob:{size:1}})),{size:1}),/40 file/);
assert.throws(()=>R.validate([{blob:{size:R.MAX_TOTAL}}],{size:1}),/100 MB/);
const original=[{id:'a'},{id:'b'},{id:'c'}];
assert.deepEqual(R.move(original,'c',-1).map(x=>x.id),['a','c','b']);
assert.deepEqual(original.map(x=>x.id),['a','b','c']);
assert.deepEqual(R.move(original,'a',-1),original);
assert.deepEqual(R.crop(1200,800,1),{x:200,y:0,w:800,h:800});
assert.deepEqual(R.crop(1200,800,0),{x:0,y:0,w:1200,h:800});
assert.equal(R.kind('unsafe.png','text/html'),'file');
assert.equal(R.nameCopy('original.jpg','png'),'original-ban-sao.png');
console.log('OK: file URL boundaries, quotas, non-destructive ordering, crop and copy naming');
